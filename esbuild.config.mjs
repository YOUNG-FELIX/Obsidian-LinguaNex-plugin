import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { createRequire } from "module";
import path from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);

const banner = `/*
LinguaNex - local MDX/MDD dictionary for Obsidian
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";

// Resolve a handful of Node builtins to browser-safe npm polyfills,
// so the bundle contains NO top-level require("fs") / require("assert") /
// require("stream") etc. (mobile WebView has no Node runtime).
const rootDir = path.dirname(fileURLToPath(import.meta.url));
const nodePolyfills = {
  buffer: "node_modules/buffer/index.js",
  process: "node_modules/process/browser.js",
  util: "node_modules/util/util.js",
  events: "node_modules/events/events.js",
};

const polyfillPlugin = {
  name: "node-polyfills",
  setup(build) {
    build.onResolve(
      { filter: /^(buffer|process|util|events)$/ },
      (args) => {
        const target = nodePolyfills[args.path];
        if (!target) return undefined;
        return { path: path.join(rootDir, target), namespace: "file" };
      }
    );
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [polyfillPlugin],
  external: ["obsidian", "electron", "@codemirror/autocomplete", "@codemirror/collab", "@codemirror/commands", "@codemirror/language", "@codemirror/lint", "@codemirror/search", "@codemirror/state", "@codemirror/view", "@lezer/common", "@lezer/highlight", "@lezer/lr", ...builtins],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  loader: { ".ttf": "dataurl", ".woff": "dataurl", ".woff2": "dataurl", ".mp3": "dataurl" }
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
